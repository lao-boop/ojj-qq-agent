/** Migrate only our exact former default; never replace a user's edited persona. */
export function ensureWecomPersona(dataDir) {
  fs.mkdirSync(dataDir,{recursive:true});
  const file=path.join(dataDir,'persona.wecom.md');
  if(!fs.existsSync(file)) fs.writeFileSync(file,DEFAULT_WECOM_PERSONA,{mode:0o600});
  else {
    const previous=fs.readFileSync(file,'utf8');
    if(previous.trim()===LEGACY_WECOM_PERSONA.trim()) {
      const backup=path.join(dataDir,'persona.wecom.before-conversation-update.md');
      if(!fs.existsSync(backup)) fs.writeFileSync(backup,previous,{mode:0o600,flag:'wx'});
      fs.writeFileSync(file,DEFAULT_WECOM_PERSONA,{mode:0o600});
    }
  }
  return file;
}

