import assert from 'node:assert/strict';
import {batchTotal} from '../src/wecom-batches.js';
const topic = '退库封条';
const q = topic+'的两批一共是多少？';
const report={exactMatter:topic,links:[]};
const row=(id,text,sender='许')=>({id,sender,text});
const first=row('first','退库封条首批点收了5箱。'), second=row('second','第二批点收5箱。','熊');
const run=(...rows)=>batchTotal(q,report,rows);
assert.deepEqual(run(first,second,row('copy','第二批复核5箱。','熊')).ids,['first','second']);
assert.match(run(first,second).text,/合计 10 箱/);
report.links.push({reply:'fix',quoted:'first',basis:'平台引用编号'});
assert.match(run(first,second,row('fix','更正，原报5箱应为3箱。')).text,/合计 8 箱/);
assert.deepEqual(run(first,row('other','第二批实收5件。')).ids,[]);
assert.deepEqual(run(first,row('unk','入库8箱。')).ids,[]);
assert.deepEqual(run(first,row('target','第二批预计收到8箱。')).ids,[]);
const combined=row('both','首批实收16套，第二批实收9套。');
assert.match(run(combined).text,/合计 25 套/);
assert.deepEqual(run(combined).ids,['both']);
assert.deepEqual(run(row('mixed','首批实收16套，第二批发出9套。')).ids,[]);
assert.deepEqual(run(combined,row('fix','更正为10套。')).ids,[]);
const {validateDirectBriefing}=await import('../src/wecom-scheduled-briefing.js');
const selected={paragraphs:[{text:'封条已点收。',evidence:[{source:'first',quote:'点收了5箱'}]}]};
assert.throws(()=>validateDirectBriefing(selected,[first,second]),/遗漏/);
assert.deepEqual(validateDirectBriefing(selected,[first,second],true).sources,['first']);
