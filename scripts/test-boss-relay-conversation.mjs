import assert from 'node:assert/strict';
import {BossRelayConversation} from '../src/boss-relay-conversation.js';
const users=['林晨','周敏','采购小王','仓储小王'].map((name,i)=>({name,userid:String(i+1)}));
const convo=new BossRelayConversation();
const turn=(text,key='boss',now=100)=>convo.prepare(key,text,users,now);
const deliveries=p=>p.items.map(x=>[x.target.name,x.text]);
assert.deepEqual(deliveries(turn('让林晨核库存，让周敏核运费')), [['林晨','核库存'],['周敏','核运费']]);
assert.match(turn('告诉林晨：先核对。再告诉小王：保留原件。').reply,/指哪位/);
assert.match(turn('小王').reply,/指哪位/);
assert.deepEqual(deliveries(turn('仓储那位')), [['林晨','先核对。'],['仓储小王','保留原件。']]);
assert.equal(turn('仓储那位'),null);
assert.match(turn('通知小王核库存').reply,/指哪位/);
assert.match(turn('不发了').reply,/取消/);
assert.equal(turn('第二位'),null);
assert.equal(turn('让林晨转述：“告诉周敏：改数量，再告诉小王：核库存。”'),null);
assert.match(turn('订单8891由周敏负责。').reply,/周敏/);
assert.match(turn('告诉她，改到周二。','other').reply,/确认/);
assert.deepEqual(deliveries(turn('告诉她，改到周二。')), [['周敏','订单8891，改到周二。']]);
assert.match(turn('告诉她，改到周五。','boss',900101).reply,/确认/);
const duplicates=[{userid:'a',name:'小李'},{userid:'b',name:'小李'}];
assert.match(convo.prepare('dup','告诉小李：确认收货。',duplicates).reply,/指哪位/);
assert.equal(convo.prepare('dup','第二位',duplicates).items[0].target.userid,'b');
console.log('conversation regression checks passed');
